"""Experiment-tracking comparison: baseline free-text citations vs structured JSON-schema
citations. Reads the eval results already produced by check_citations.py / check_citations_structured.py
— doesn't duplicate that data, just summarizes it into one table.
"""
import json
from pathlib import Path

EVAL_DIR = Path(__file__).parent.parent.parent / "data" / "processed" / "eval"
OUTPUT_PATH = EVAL_DIR / "comparison.md"

RUNS = [
    ("Baseline (free-text citations)", "citation_accuracy_baseline_free_text_v1.json"),
    ("Structured (JSON-schema citations)", "citation_accuracy_structured_citations_v1.json"),
]


def load_run(filename: str) -> dict:
    path = EVAL_DIR / filename
    if not path.exists():
        raise FileNotFoundError(f"No eval results at {path} — run the corresponding generate + check scripts first.")
    return json.loads(path.read_text())


def pct(value) -> str:
    return f"{value * 100:.1f}%" if value is not None else "N/A"


def build_table(runs: list) -> str:
    labels = [label for label, _ in runs]
    data = [load_run(filename) for _, filename in runs]

    rows = [
        ("Schema compliance", [pct(d.get("format_compliance")) for d in data]),
        ("Citation accuracy", [pct(d.get("overall_accuracy")) for d in data]),
        ("Total citations", [str(d.get("total_citations")) for d in data]),
        ("Verified citations", [str(d.get("total_verified")) for d in data]),
    ]

    lines = [
        "| Metric | " + " | ".join(labels) + " |",
        "|" + "---|" * (len(labels) + 1),
    ]
    for name, values in rows:
        lines.append(f"| {name} | " + " | ".join(values) + " |")
    return "\n".join(lines)


def run():
    table = build_table(RUNS)
    print(table)

    OUTPUT_PATH.write_text(
        "# Candor citation-grounding experiment comparison\n\n"
        "Generated by `python -m src.eval.compare_runs` from data/processed/eval/*.json.\n\n"
        f"{table}\n\n"
        "Switching from free-text citations (regex-parsed `\"quote\" [mm:ss]` markers) to a "
        "JSON-schema-constrained response forced every claim to carry an exact, copy-verbatim "
        "citation — eliminating the paraphrasing and malformed-timestamp failures that caused "
        "the baseline's accuracy gap.\n"
    )
    print(f"\n-> {OUTPUT_PATH}")


if __name__ == "__main__":
    run()
